"""Generate and validate Open5GS + UERANSIM configs from a NetworkIntent.

Generation starts from the template's working scenario (configs/basic/ueransim,
compose-files/basic/ueransim) and only changes the values the intent controls,
so the result stays close to a configuration that is known to work.
"""
from __future__ import annotations

import copy
from pathlib import Path

import yaml

from .intent import NetworkIntent

REPO = Path(__file__).resolve().parents[2]
BASE_CONFIGS = REPO / "configs" / "basic" / "ueransim"
BASE_COMPOSE = REPO / "compose-files" / "basic" / "ueransim" / "docker-compose.yaml"
GEN_CONFIGS = REPO / "configs" / "generated"
GEN_COMPOSE = REPO / "compose-files" / "generated"

CORE_NFS = ["nrf", "ausf", "udm", "udr", "nssf", "bsf", "pcf", "amf", "smf", "upf"]
GNB_ALIAS = "gnb.ueransim.org"
AMF_ALIAS = "amf.open5gs.org"


def _load(path: Path) -> dict:
    with open(path) as f:
        return yaml.safe_load(f)


def _dump(data: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        f.write("# Generated by src/provisioning/configgen.py - do not edit by hand\n")
        yaml.safe_dump(data, f, sort_keys=False, default_flow_style=False)


def _plmn(intent: NetworkIntent) -> dict:
    # Strings keep leading zeros ("001", "01"); YAML would turn 001 into 1.
    return {"mcc": str(intent.mcc), "mnc": str(intent.mnc)}


def paths_for(name: str) -> tuple[Path, Path]:
    return GEN_CONFIGS / name, GEN_COMPOSE / name / "docker-compose.yaml"


# --------------------------------------------------------------------------
# Generation
# --------------------------------------------------------------------------
def create_config(intent: NetworkIntent) -> dict:
    """Write all NF/gNB/UE configs and a compose file for this intent."""
    intent.validate()
    cfg_dir, compose_path = paths_for(intent.name)
    slices = intent.slices

    # Core NFs: copy, then patch PLMN/TAC/slices/subnet where they appear.
    for nf in CORE_NFS:
        data = _load(BASE_CONFIGS / f"{nf}.yaml")
        if nf == "amf":
            amf = data["amf"]
            for g in amf["guami"]:
                g["plmn_id"] = _plmn(intent)
            amf["tai"] = [{"plmn_id": _plmn(intent), "tac": int(intent.tac)}]
            amf["plmn_support"] = [{
                "plmn_id": _plmn(intent),
                "s_nssai": [{"sst": sst, "sd": sd} for sst, sd in slices],
            }]
        elif nf == "nssf":
            nsi = data["nssf"]["sbi"]["client"]["nsi"]
            template = nsi[0]
            data["nssf"]["sbi"]["client"]["nsi"] = []
            for sst, sd in slices:
                entry = copy.deepcopy(template)
                entry["s_nssai"] = {"sst": sst, "sd": sd}
                data["nssf"]["sbi"]["client"]["nsi"].append(entry)
        elif nf in ("smf", "upf"):
            data[nf]["session"][0]["subnet"] = intent.ue_subnet
        _dump(data, cfg_dir / f"{nf}.yaml")

    # gNB
    gnb = _load(BASE_CONFIGS / "gnb.yaml")
    gnb.update(_plmn(intent))
    gnb["tac"] = int(intent.tac)
    gnb["slices"] = [{"sst": sst, "sd": sd} for sst, sd in slices]
    _dump(gnb, cfg_dir / "gnb.yaml")

    # One UE config per UE
    base_ue = _load(BASE_CONFIGS / "ue.yaml")
    for i, u in enumerate(intent.ues, 1):
        ue = copy.deepcopy(base_ue)
        ue.update(_plmn(intent))
        ue["supi"] = f"imsi-{u.imsi}"
        ue["key"], ue["op"], ue["opType"] = u.key, u.opc, "OPC"
        ue["sessions"] = [{"type": "IPv4", "apn": u.apn, "slice": {"sst": u.sst, "sd": u.sd}}]
        ue["configured-nssai"] = [{"sst": u.sst, "sd": u.sd}]
        ue["default-nssai"] = [{"sst": u.sst, "sd": u.sd}]
        _dump(ue, cfg_dir / f"ue{i}.yaml")

    _write_compose(intent, compose_path)
    _dump(intent.to_dict(), cfg_dir / "intent.yaml")
    return {"config_dir": str(cfg_dir.relative_to(REPO)),
            "compose_file": str(compose_path.relative_to(REPO)),
            "ues": [f"ue{i}" for i in range(1, len(intent.ues) + 1)]}


def _write_compose(intent: NetworkIntent, compose_path: Path) -> None:
    compose = _load(BASE_COMPOSE)
    rel = f"../../../configs/generated/{intent.name}"
    for key, cfg in compose["configs"].items():
        cfg["file"] = f"{rel}/{Path(cfg['file']).name}"

    base_ue = compose["services"].pop("ue")
    compose["configs"].pop("ue_config")
    for i in range(1, len(intent.ues) + 1):
        svc = copy.deepcopy(base_ue)
        svc["container_name"] = f"ue{i}"
        svc["networks"]["open5gs"]["aliases"] = [f"ue{i}.ueransim.org"]
        svc["configs"] = [{"source": f"ue{i}_config", "target": "/UERANSIM/config/ue.yaml"}]
        compose["services"][f"ue{i}"] = svc
        compose["configs"][f"ue{i}_config"] = {"file": f"{rel}/ue{i}.yaml"}
    _dump(compose, compose_path)


# --------------------------------------------------------------------------
# Validation (cross-file consistency, before anything is started)
# --------------------------------------------------------------------------
def _norm_mcc(v) -> str:
    return str(v).zfill(3)


def _norm_mnc(v) -> str:
    return str(v).zfill(2)


def validate_config(name: str) -> dict:
    """Check that AMF, gNB, UEs, NSSF, SMF and UPF agree with each other.

    Returns {"ok": bool, "errors": [...], "checks": n}. Typical errors found here are
    exactly the ones Group 3 (Troubleshooting) injects on purpose: PLMN / TAC / slice /
    subnet mismatches.
    """
    cfg_dir, compose_path = paths_for(name)
    errors: list[str] = []
    checks = 0

    def check(cond: bool, msg: str) -> None:
        nonlocal checks
        checks += 1
        if not cond:
            errors.append(msg)

    if not cfg_dir.exists():
        return {"ok": False, "errors": [f"no generated config for '{name}'"], "checks": 0}

    amf = _load(cfg_dir / "amf.yaml")["amf"]
    gnb = _load(cfg_dir / "gnb.yaml")
    nssf = _load(cfg_dir / "nssf.yaml")["nssf"]
    smf = _load(cfg_dir / "smf.yaml")["smf"]
    upf = _load(cfg_dir / "upf.yaml")["upf"]
    ue_files = sorted(cfg_dir.glob("ue*.yaml"))

    plmn = (_norm_mcc(gnb["mcc"]), _norm_mnc(gnb["mnc"]))
    for section in ("guami", "tai", "plmn_support"):
        for entry in amf[section]:
            p = entry["plmn_id"]
            check((_norm_mcc(p["mcc"]), _norm_mnc(p["mnc"])) == plmn,
                  f"AMF {section} PLMN {p['mcc']}/{p['mnc']} != gNB PLMN {plmn[0]}/{plmn[1]}")

    check(any(int(t["tac"]) == int(gnb["tac"]) for t in amf["tai"]),
          f"gNB TAC {gnb['tac']} not served by AMF (AMF TAI list: {[t['tac'] for t in amf['tai']]})")

    amf_slices = {(int(s["sst"]), int(s.get("sd", 0)))
                  for ps in amf["plmn_support"] for s in ps["s_nssai"]}
    gnb_slices = {(int(s["sst"]), int(s.get("sd", 0))) for s in gnb["slices"]}
    nssf_slices = {(int(n["s_nssai"]["sst"]), int(n["s_nssai"].get("sd", 0)))
                   for n in nssf["sbi"]["client"]["nsi"]}
    check(gnb_slices <= amf_slices, f"gNB slices {gnb_slices} not all supported by AMF {amf_slices}")
    check(gnb_slices <= nssf_slices, f"gNB slices {gnb_slices} not all known to NSSF {nssf_slices}")

    check(any(c["address"] == AMF_ALIAS for c in gnb["amfConfigs"]),
          f"gNB amfConfigs does not point to {AMF_ALIAS}")
    check(smf["session"][0]["subnet"] == upf["session"][0]["subnet"],
          f"SMF subnet {smf['session'][0]['subnet']} != UPF subnet {upf['session'][0]['subnet']}")

    check(len(ue_files) > 0, "no UE configs found")
    for f in ue_files:
        ue = _load(f)
        tag = f.stem.upper()
        check((_norm_mcc(ue["mcc"]), _norm_mnc(ue["mnc"])) == plmn,
              f"{tag} PLMN {ue['mcc']}/{ue['mnc']} != network PLMN {plmn[0]}/{plmn[1]}")
        check(str(ue["supi"]).startswith(f"imsi-{plmn[0]}{plmn[1]}"),
              f"{tag} SUPI {ue['supi']} does not start with PLMN {plmn[0]}{plmn[1]}")
        check(GNB_ALIAS in ue["gnbSearchList"], f"{tag} gnbSearchList does not contain {GNB_ALIAS}")
        for s in ue["sessions"]:
            sl = (int(s["slice"]["sst"]), int(s["slice"].get("sd", 0)))
            check(sl in gnb_slices, f"{tag} slice {sl} not offered by gNB {gnb_slices}")

    if compose_path.exists():
        compose = _load(compose_path)
        for key, cfg in compose["configs"].items():
            target = (compose_path.parent / cfg["file"]).resolve()
            check(target.exists(), f"compose config '{key}' points to missing file {cfg['file']}")
    else:
        check(False, f"compose file {compose_path} missing")

    return {"ok": not errors, "errors": errors, "checks": checks}
